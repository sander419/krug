/* Зажать значение в границы. */
export const clamp = (v, a, b) => Math.min(b, Math.max(a, v));

/* Округление до знака. Рецепт уезжает в ссылку целиком, а восемнадцать знаков
   после запятой в ней — это лишние сотни символов и ноль пользы: 0,0001 доли
   высоты это сотая миллиметра. */
export const round = (v, n = 4) => {
  const k = Math.pow(10, n);
  return Math.round(v * k) / k;
};

/* Плавное затухание 0…1 — для переходов между этапами. */
export const smoothstep = f => f * f * (3 - 2 * f);
