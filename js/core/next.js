// «Что делать дальше»: путь от формы до производства, шаг за шагом.
//
// Инструмент знает больше, чем человек успевает спросить. Восемь вкладок и
// сорок блоков — это карта, а человеку нужен маршрут: сделал форму — выбери
// массу, выбрал массу — проверь стенку, проверил — посчитай печь, посчитал —
// забери лист. Раньше он должен был угадать этот порядок сам.
//
// Здесь только правила, без DOM. Шаг — это утверждение о состоянии, которое
// либо выполнено, либо нет, и адрес, куда идти его выполнять. Ни один шаг
// не выдумывает работу: каждый смотрит на то, что уже считается.
//
// Правило честности: шаг «сделано» ставится по факту (масса выбрана, замечаний
// нет, печь считает цену), а не по тому, открывал ли человек вкладку.

/**
 * @param ctx {state, prod, warnings, kiln, cost, exported}
 * @returns [{id, name, hint, done, blocked, go:{tab, block}}]
 */
export function nextSteps(ctx) {
  const {state, prod, warnings = [], kiln = {}, cost = {}} = ctx;
  const bad = warnings.filter(w => w.lvl === 'bad');
  const warn = warnings.filter(w => w.lvl === 'warn');
  const parts = state.parts || [];
  const lidOn = !!(state.lid && state.lid.on);

  const steps = [];
  const add = (id, name, hint, done, go, opt = {}) =>
    steps.push({id, name, hint, done: !!done, go, ...opt});

  /* 1. Форма. «Сделано» — когда профиль отличается от пресета по умолчанию
        хоть чем-то: человек взял пресет, потянул точку или обвёл картинку. */
  add('form', 'Задайте форму',
      'Возьмите пресет, тяните точки на чертеже или обведите фотографию.',
      Array.isArray(state.points) && state.points.length >= 2,
      {tab: 'form', block: 'presets'});

  /* 2. Размеры: высота и диаметр — сырые, до обжига. Всегда заданы, но шаг
        нужен как напоминание, что числа именно на круге. */
  add('size', 'Проверьте размеры на круге',
      `Сейчас ${Math.round(state.H)}×${Math.round(state.D)} мм — это до обжига. После усадки будет меньше.`,
      true, {tab: 'form', block: 'size'});

  /* 3. Масса: от неё усадка, цвет и температура. Без неё дальше считать нечего. */
  add('mat', 'Выберите массу',
      'От массы зависит усадка, температура обжига и цена глины.',
      !!state.mat, {tab: 'mat', block: 'matlib'});

  /* 4. Стенка и устойчивость: пока есть красные замечания, производство
        обсуждать рано — изделие развалится или не встанет. */
  add('check', bad.length ? 'Исправьте замечания мастера' : 'Замечания мастера',
      bad.length
        ? `${bad.length} ${plural(bad.length, 'замечание', 'замечания', 'замечаний')} уровня «нельзя»: ${bad[0].txt}`
        : warn.length
          ? `Красных нет, есть ${warn.length} ${plural(warn.length, 'предупреждение', 'предупреждения', 'предупреждений')} — прочтите перед производством.`
          : 'Форма технологична и устойчива.',
      bad.length === 0, {panel: 'warn'}, {alarm: bad.length > 0});

  /* 5. Прилепы и крышка — только если они есть: не навязываем ручку тому,
        кто делает вазу. */
  if (parts.length || lidOn)
    add('parts', 'Проверьте прилепы и крышку',
        lidOn
          ? 'Зазор посадки крышки считается после обжига — посмотрите, сядет ли.'
          : 'Ручки и носики держат замечания наравне с корпусом.',
        true, {tab: 'form', block: parts.length ? 'parts' : 'lid'});

  /* 6. Печь: садка даёт цену обжига, без неё себестоимость неполная. */
  add('kiln', 'Посчитайте печь',
      kiln.perItem
        ? `Входит ${kiln.load && kiln.load.total} шт за обжиг, ${Math.round(kiln.perItem)} ₽ на изделие.`
        : 'Изделие не входит в выбранную печь или печь не задана — обжиг не попадёт в себестоимость.',
      !!kiln.perItem, {tab: 'mat', block: 'kiln'});

  /* 7. Деньги: себестоимость считается всегда, но «сделано» — когда в ней
        нет пустых мест (цена массы и обжиг известны). */
  add('cost', 'Посчитайте себестоимость',
      cost.complete
        ? `Изделие обходится в ${Math.round(cost.total)} ₽, продавать дешевле ${Math.round(cost.minPrice)} ₽ нельзя.`
        : 'В смете есть пустые места: цена массы или обжиг не посчитаны.',
      !!cost.complete, {tab: 'money', block: 'piececost'});

  /* 8. Выгрузка: чем работа заканчивается — лист для мастерской и модель. */
  add('out', 'Заберите результат',
      'Лист A3 с тремя видами и таблицей — для мастерской; STL — для печати и формы.',
      !!ctx.exported, {menu: 'export'});

  return steps;
}

/** Первый невыполненный шаг — то, что показывает полоса «дальше». */
export function currentStep(steps) {
  return steps.find(s => !s.done) || null;
}

function plural(n, one, few, many) {
  const m10 = n % 10, m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return one;
  if (m10 >= 2 && m10 <= 4 && (m100 < 10 || m100 >= 20)) return few;
  return many;
}
