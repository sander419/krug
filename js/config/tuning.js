// Пороги инструмента, которые можно поставить свои.
//
// В КРУГе десятки чисел вида «уклон меньше 1,5° — изделие липнет к форме» или
// «зазор между изделиями в печи 15 мм». Все они — умолчания этого инструмента,
// а не отраслевой норматив, и это написано в каждом окне. Но пока их нельзя было
// поменять, любая мастерская со своей практикой упиралась в чужую цифру:
// у кого-то гипс держит зазор 10 мм, у кого-то ручка тоньше, у кого-то печь
// греет иначе.
//
// Поэтому все такие числа собраны здесь, в одном реестре, и каждое можно
// переопределить. Правила реестра:
//
//   • у параметра есть предел разумного (min/max) — за него не пустят;
//   • у параметра написано, ЧТО ИМЕННО он меняет, а не только как называется:
//     иначе крутить его вслепую;
//   • параметр обязан на что-то влиять — это проверяет tools/check-tuning.mjs;
//   • свои значения уезжают в ссылку-ДНК вместе с рецептом, иначе у автора
//     и у получателя сойдутся формы, но разойдутся числа.
//
// Умолчания здесь — те же, что стояли в коде до появления настроек: включённый
// инструмент считает ровно так же, как считал.

