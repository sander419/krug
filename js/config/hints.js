// не обязан знать, что «уклон 1,5°» — это про выемку из формы, а «2,9×» —
// это запас стенки у основания. Пока подсказки жили в `title` разметки, они
// были короткими («Толщина стенки») и отвечали на вопрос «как называется»,
// а не «что мне с этим делать».
//
// Здесь подсказки лежат данными, отдельно от разметки:
//
//   • их видно списком — сразу понятно, где пусто;
//   • они переживают перерисовку экранов, которые собираются из строк;
//   • у каждой может быть статья энциклопедии — «почему» на один клик;
//   • их проверяет `tools/check-hints.mjs`: селектор существует, текст не пуст,
//     статья есть в базе знаний.
//
// Правило текста: первая фраза — что это, вторая — что с этим делать или чем
// это грозит. Без «нажмите сюда, чтобы».
//
