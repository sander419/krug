// Печи: во что ставят изделие и чем за это платят.
//
// Обжиг — самая дорогая операция у гончара и единственная, цену которой нельзя
// поделить на изделие, не посчитав садку: печь берёт киловатты за цикл, а не
// за штуку. Поставить в неё три чашки или двенадцать — разница в себестоимости
// вчетверо, и решается она размерами камеры, а не прайсом.
//
// Здесь типовые классы печей, а не модели: у каждого производителя своя линейка,
// и точные габариты камеры пишут в паспорте — их и надо брать. Поэтому все числа
// помечены est, а в интерфейсе есть «свои размеры»: это главный путь, а список —
// чтобы было с чего начать.
//
// СОГЛАШЕНИЕ О ДАННЫХ (одинаковое во всех реестрах проекта):
//   est     — значение посчитано или взято по типу, а не из паспорта;
//   unknown — данных нет, надо уточнять у поставщика;
//   na      — величина к этой записи неприменима.
// Проверка: node tools/check-kilns.mjs

